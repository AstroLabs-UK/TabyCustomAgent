export function gifForAnimationId(id: string): string | null {
  if (GIF_PATHS[id]) return GIF_PATHS[id];
  // alias common shorts
  const aliases: Record<string, string> = {
    idle: "idle_01_loop",
    thinking: "working_loop",
    done: "confirmation",
    yes: "thumbs_up",
  };
  const a = aliases[id];
  return a && GIF_PATHS[a] ? GIF_PATHS[a] : null;
}

